const KEY = 'fs-lang';
function initial() {
  try { const s = localStorage.getItem(KEY); if (s === 'en' || s === 'zh') return s; } catch {}
  return /^zh/i.test(navigator.language || '') ? 'zh' : 'en';
}
export let lang = initial();

export function t(key, vars) {
  let s = lang === 'zh' && ZH[key] != null ? ZH[key] : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
  return s;
}
// Pick the Chinese or English version of a server-provided value
export function L(en, zh) {
  if (lang === 'zh' && zh != null && zh !== '' && !(Array.isArray(zh) && !zh.length)) return zh;
  return en;
}
export const locale = () => (lang === 'zh' ? 'zh-HK' : 'en-HK');

export function setLang(l) {
  lang = l === 'zh' ? 'zh' : 'en';
  try { localStorage.setItem(KEY, lang); } catch {}
  applyStatic();
}

// Static page text: elements carry data-i18n (text), data-i18n-ph (placeholder),
// data-i18n-aria (aria-label) and data-i18n-title (title) holding the English key.
export function applyStatic(root = document) {
  document.documentElement.lang = lang === 'zh' ? 'zh-HK' : 'en';
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  const b = document.getElementById('langBtn');
  if (b) {
    b.querySelector('.lang-now').textContent = lang === 'zh' ? 'EN' : '中';
    b.setAttribute('aria-label', lang === 'zh' ? 'Switch to English' : '切換至中文');
    b.title = lang === 'zh' ? 'English' : '中文';
  }
}
